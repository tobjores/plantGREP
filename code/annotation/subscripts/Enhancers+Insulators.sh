ATACCTTTTCTTGCCATACCATTTAGCCGATCAATT" >> ${OUTDIR}/Insulators.fa

fi


### tile across the full-length insulators ###
awk '{
    if (substr($1, 1, 1) == ">") {
      if ($0 ~ /TBS/) {name = ">TBS"; step = 84}
      else {name = $1; step = 72}}
    else {sequences[name":"step] = sequences[name":"step] $1}}
    END{for (seq in sequences) {
      split(seq, nast, ":");
      name = nast[1]; step = nast[2]; sequence = sequences[seq]; id = 1
      for (i = 1; i <= length(sequence) - 169; i += step) {
        print name"-"id"\n"substr(sequence, i, 170);
        id += 0.5
      }
    }}' ${OUTDIR}/Insulators.fa \
  > ${OUTDIR}/Insulator_tiles.fa


### combine ###
cat ${OUTDIR}/Enhancers.fa ${OUTDIR}/Insulator_tiles.fa > ${OUTDIR}/Enhancers+Insulators_final.fa