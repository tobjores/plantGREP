CGTCCAACATATGGCACCGGAGGCTTTCGTCTTCAC" >> ${OUTDIR}/Insulators.fa
  echo ">gypsy" >> ${OUTDIR}/Insulators.fa
  echo -e "CACGTAATAAGTGTGCGTTGAATTTATTCGCAAAAACATTGCATATTTTCGGCAAAGTAAAATTTTGTTG\n\
CATACCTTATCAAAAAATAAGTGCTGCATACTTTTTAGAGAAACCAAATAATTTTTTATTGCATACCCGT\n\
