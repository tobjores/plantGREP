### get insulator sequences ###
if [ ! -f "${OUTDIR}/Insulators.fa" ]; then
  curl "https://www.ncbi.nlm.nih.gov/sviewer/viewer.fcgi?id=214003639&db=nuccore&report=fasta&retmode=text" \
    | awk '$0 != ""' \
    > ${OUTDIR}/Insulators.fa
  echo ">sIns1" >> ${OUTDIR}/Insulators.fa
  echo -e "AGAACTTTAAAAGTGCTCATCATTGGAAAACGTTCTTCGGGGCGAAAACTCTCAAGGATCTTACCGCTGT\n\
TGAGATCCAGTTCGATGTAACCCACTCGTGCACCCAACTGATCTTCAGCATCTTTTACTTTCACCAGCGT\n\
